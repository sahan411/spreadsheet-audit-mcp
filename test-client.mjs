import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
const HERE = dirname(fileURLToPath(import.meta.url));
const PY = process.env.PYTHON || (process.platform === "win32" ? "python" : "python3");
const DIR = mkdtempSync(join(tmpdir(), "xa-"));
const gen = spawnSync(PY, [join(HERE, "fixtures.py"), DIR], { encoding: "utf8" });
if (gen.status !== 0) { console.error(gen.stderr); process.exit(2); }
const c = new Client({ name: "test", version: "0" });
await c.connect(new StdioClientTransport({ command: "node", args: [join(HERE, "server.mjs")] }));
let pass = 0, fail = 0;
const check = (n, ok, x = "") => { ok ? pass++ : fail++; console.log(ok ? "PASS" : "FAIL", n, x); };
check("lists 2 tools", (await c.listTools()).tools.map((t) => t.name).sort().join() === "audit_workbook,inspect_cell");
const b = (await c.callTool({ name: "audit_workbook", arguments: { path: join(DIR, "broken.xlsx") } })).structuredContent;
const rules = new Set(b.findings.map((f) => f.rule));
check("broken: finds typed-over, pattern break, calc error", ["TYPED-OVER", "PATTERN-BREAK", "CALC-ERROR"].every((r) => rules.has(r)), [...rules].join());
check("broken: HIGH count >= 3", (b.counts.HIGH || 0) >= 3, JSON.stringify(b.counts));
const k = (await c.callTool({ name: "audit_workbook", arguments: { path: join(DIR, "clean.xlsx"), min_severity: "MEDIUM" } })).structuredContent;
check("clean: nothing at MEDIUM or above", k.findings.length === 0, JSON.stringify(k.counts));
const x = (await c.callTool({ name: "audit_workbook", arguments: { path: join(DIR, "ext.xlsx"), recalc: false } })).structuredContent;
check("external link flagged", x.findings.some((f) => f.rule === "EXT-LINK"));
const i = (await c.callTool({ name: "inspect_cell", arguments: { path: join(DIR, "broken.xlsx"), sheet: "Sales", cell: "E6" } })).structuredContent;
check("inspect_cell returns formula and reads", i.value_or_formula === "=D6*0.09" && i.reads.includes("D6"), JSON.stringify(i.reads));
const bad = await c.callTool({ name: "audit_workbook", arguments: { path: join(DIR, "nope.xlsx") } });
check("missing file -> isError", bad.isError === true);
const txt = await c.callTool({ name: "audit_workbook", arguments: { path: join(HERE, "package.json") } });
check("non-xlsx rejected", txt.isError === true);
console.log(`\n${pass} passed, ${fail} failed`);
await c.close(); rmSync(DIR, { recursive: true, force: true });
process.exit(fail ? 1 : 0);
